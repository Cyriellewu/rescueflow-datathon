"""Write docs/evaluation.md and docs/data_audit.md from the artifacts, so every number in the
pitch comes from one place. Run after run_pipeline.py and run_policy_lab.py.

    python scripts/write_report.py --art artifacts
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAMES = {"xgboost": "RescueNYC (xgboost, queue-aware)", "demand_only": "Demand-only xgboost (H1 control)",
         "hour_of_week_rate": "Hour-of-week history", "persistence": "Persistence (stressed now)",
         "backlog_logistic": "Backlog-only logistic"}
LAB = {"baseline": "baseline", "handover_shock": "handover shock", "shock_baseline": "shock, no reserves",
       "shock_reactive": "shock, reactive reserves", "shock_ai": "shock, AI-warned reserves"}


def f(v, d=3):
    return "–" if v is None else f"{v:.{d}f}"


def ci(c, d=2):
    return f"{c['diff']:+.{d}f} ({c['ci95'][0]:+.{d}f} to {c['ci95'][1]:+.{d}f})"


def verdict(c):
    return "detectable" if c["ci95"][0] > 0 or c["ci95"][1] < 0 else "no clear difference"


BANNER = ("> **SYNTHETIC PLACEHOLDER.** These numbers come from the test simulator, not FDNY data. "
          "Regenerate with `scripts/write_report.py` after running the pipeline on real data. Do not quote them.\n")


def evaluation(meta, lab, source):
    ev, cas = meta["evaluation"], meta["cascade"]
    w = meta["windows"]
    out = [f"# RescueNYC — Evaluation\n"] + ([BANNER] if meta.get("data_source") == "SYNTHETIC" else []) + [
           f"Generated by `scripts/write_report.py` from `{source}`. Data source: **{meta.get('data_source', 'FDNY')}**."
           f" Model `{meta['model_version']}` trained on `{meta['trained_on']}`.\n",
           "## Early-warning model (held-out, chronological)\n",
           f"Train {w['train'][0][:10]} → {w['train'][1][:10]}, validation {w['val'][0][:10]} → {w['val'][1][:10]}, "
           f"test {w['test'][0][:10]} → {w['test'][1][:10]}. Label: next-hour median dispatch delay of severity 1–3 "
           "calls above the borough's trailing 8-week same-hour p80. Each model alerts on its own top 10% of "
           "validation hours.\n",
           "| Model | PR-AUC (95% CI) | Alert precision | Alert recall | Onset recall | Lead (h) | False alerts/day | Brier |",
           "|---|---|---|---|---|---|---|---|"]
    for k, r in ev.items():
        out.append(f"| {NAMES.get(k, k)} | {f(r['pr_auc'])} ({f(r['pr_auc_ci95'][0])}–{f(r['pr_auc_ci95'][1])}) | "
                   f"{f(r['alert_precision'], 2)} | {f(r['alert_recall'], 2)} | {f(r['onset_recall'], 2)} | "
                   f"{f(r['mean_lead_h'], 1)} | {f(r['false_alerts_per_day'], 1)} | {f(r['brier'])} |")
    base = next(iter(ev.values()))["base_rate"]
    x, d = ev["xgboost"], ev.get("demand_only")
    out += [f"\nBase rate {base:.2f}, {next(iter(ev.values()))['n']} borough-hours, "
            f"{x['n_onsets']} onsets (normal → stressed).\n",
            "### Hypotheses\n",
            f"- **H1 queue state beats demand:** PR-AUC {f(x['pr_auc'])} vs {f(d['pr_auc']) if d else '–'} for demand-only. "
            + ("CIs overlap — not established." if d and x["pr_auc_ci95"][0] <= d["pr_auc_ci95"][1] else "CIs do not overlap."),
            f"- **H2 severity mix matters (cascade test):** adding the low-acuity backlog changes PR-AUC by "
            f"{cas['delta']:+.3f} (95% CI {cas['delta_ci95'][0]:+.3f} to {cas['delta_ci95'][1]:+.3f}).",
            f"- **H3 earlier detection of new episodes:** onset recall {f(x['onset_recall'], 2)} vs persistence "
            f"{f(ev['persistence']['onset_recall'], 2)} (persistence cannot catch onsets by construction).\n",
            "Lead-time profile (mean z-score of the low-acuity backlog around onsets; lag 0 = cutoff before the stressed hour):\n",
            "| lag (h) | at onsets | all hours |", "|---|---|---|"]
    out += [f"| {p['lag_h']} | {f(p['mean_z_at_onset'], 2)} | {f(p['mean_z_all'], 2)} |" for p in meta["lead_time_profile"]]
    if lab:
        sc = lab["scenario"]
        out += ["\n## Policy lab (SIMULATION)\n",
                f"Calls replayed from **{lab['data_source']}** for the week of {lab['eval_week']}; warning model trained on "
                f"weeks {', '.join(lab['train_weeks'])}. {lab['seeds']} seeds per arm, common random numbers, run on "
                f"`{lab['computed_on']}`. Fleet, handover and cross-borough travel are **scenario assumptions**; units "
                f"per borough calibrated to the pre-test median dispatch wait: "
                f"{', '.join(f'{b.title()} {n}' for b, n in sc['units'].items())}. Shock: {lab['shock']['borough'].title()} "
                f"handover ×{lab['shock']['factor']} for hours {lab['shock']['start_h']}–{lab['shock']['end_h']} of the week.\n"]
        for title, key in [("Experiment 1 — does a handover shock spread?", "experiment1"),
                           ("Experiment 2 — does the warning help under the same reserve budget?", "experiment2")]:
            out += [f"### {title}\n", "| Comparison | Metric | A | B | B − A (95% CI) | |", "|---|---|---|---|---|---|"]
            out += [f"| {LAB[c['b']]} vs {LAB[c['a']]} | {c['metric']} | {c['mean_a']:.2f} | {c['mean_b']:.2f} | {ci(c)} | {verdict(c)} |"
                    for c in lab[key]]
            out.append("")
        out.append(f"Reserve use per arm: {json.dumps(lab['reserve_use'])}\n")
    out += ["## Limitations\n",
            "- Historical replay of published records, not a live CAD feed; FDNY publishes with a lag of months.",
            "- The backlog is reconstructed from timestamps after the fact; real-time availability of each field is assumed, not verified.",
            "- FDNY's response measure is not the Comptroller's end-to-end time; they are not compared on one axis.",
            "- Bottleneck tags and at-hospital counts are contributing indicators, not causes; incident close ≠ unit available.",
            "- Policy-lab results depend on scenario assumptions and say nothing about real-world minutes saved.\n"]
    return "\n".join(out)


def audit(a, synthetic=False):
    rows = [("Rows (raw → clean)", f"{a['rows_raw']:,} → {a['rows_clean']:,}"),
            ("Date range", f"{a['date_min']} → {a['date_max']}"),
            ("Published vs recomputed dispatch seconds, mismatch > 1 s", f"{a['dispatch_mismatch_rate']:.3%}"),
            ("Valid dispatch durations", f"{a['dispatch_valid_rate']:.1%}"),
            ("Valid travel durations", f"{a['travel_valid_rate']:.1%}"),
            ("Held calls", f"{a['held_rate']:.1%}"),
            ("Median dispatch, held vs not held (s)", f"{a['median_dispatch_held_s']:.0f} vs {a['median_dispatch_not_held_s']:.0f}"),
            ("Calls with a hospital arrival", f"{a.get('hosp_arrival_rate', 0):.1%}"),
            ("Median hospital arrival → close (min)", f"{a.get('median_hosp_to_close_min') or 0:.0f}"),
            ("Replay engine", f"{a['replay']['events']:,} events, {a['replay']['events_per_s']:,.0f} events/s")]
    out = ["# RescueNYC — Data audit\n"] + ([BANNER] if synthetic else []) + ["Generated by `scripts/write_report.py` from `data_audit.json`.\n",
           "| Check | Result |", "|---|---|"] + [f"| {k} | {v} |" for k, v in rows]
    out += ["\nSeverity codes: " + ", ".join(f"{k}: {v:,}" for k, v in a["severity_counts"].items()),
            "\nBoroughs: " + ", ".join(f"{k}: {v:,}" for k, v in a["boroughs"].items()),
            "\n**Still to check by hand:** held calls should have much longer dispatch times than non-held "
            "(else drop `held_indicator`); severity code set stable across years; gap between incident close "
            "and unit availability for the at-hospital proxy."]
    return "\n".join(out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--art", type=Path, default=Path("artifacts"))
    args = ap.parse_args()
    meta = json.loads((args.art / "meta.json").read_text())
    lab_path = args.art / "policy_lab.json"
    lab = json.loads(lab_path.read_text()) if lab_path.exists() else None
    (ROOT / "docs" / "evaluation.md").write_text(evaluation(meta, lab, args.art))
    (ROOT / "docs" / "data_audit.md").write_text(audit(json.loads((args.art / "data_audit.json").read_text()),
                                                    meta.get("data_source") == "SYNTHETIC"))
    print("wrote docs/evaluation.md and docs/data_audit.md")
