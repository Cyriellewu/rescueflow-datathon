"""Run everything: load calls -> build table -> train -> evaluate -> write results/.

    python -m rescuenyc.run [--raw data/raw]
"""
import argparse
import json
import platform
import time
from pathlib import Path

import pandas as pd
from sklearn.inspection import permutation_importance

from rescuenyc import config
from rescuenyc.evaluate import evaluate
from rescuenyc.examples import label_examples, pick_segments, plot_window
from rescuenyc.load import load_calls
from rescuenyc.models import fit_all
from rescuenyc.table import FEATURES, build_table


def md_table(df, floats="{:.2f}"):
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(floats.format(v) if isinstance(v, float) else str(v) for v in r) + " |")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", default=str(config.RAW))
    args = ap.parse_args()
    out = config.OUT
    out.mkdir(parents=True, exist_ok=True)
    t0 = time.time()

    calls, data_summary = load_calls(Path(args.raw))
    print(f"loaded {len(calls):,} calls in {time.time() - t0:.0f}s")
    table = build_table(calls)
    print(f"table {len(table):,} borough-hours in {time.time() - t0:.0f}s")

    lab = table[table["stressed"].notna()]
    train = lab[lab["hour"] < config.VAL_START]
    val = lab[(lab["hour"] >= config.VAL_START) & (lab["hour"] < config.TEST_START)]
    test = lab[lab["hour"] >= config.TEST_START]

    methods, full = fit_all(train)
    print(f"trained in {time.time() - t0:.0f}s")
    results, alerts, scores = evaluate(methods, val, test)
    print(results.to_string())

    imp = permutation_importance(full, test[FEATURES], test["stressed"].astype(int), scoring="average_precision",
                                 n_repeats=3, random_state=config.SEED)
    importance = (pd.DataFrame({"input": FEATURES, "PR-AUC drop when shuffled": imp.importances_mean})
                  .sort_values("PR-AUC drop when shuffled", ascending=False))

    segments, _ = pick_segments(test, scores, alerts)
    plot_window(test, scores, alerts, "BROOKLYN", pd.Timestamp("2026-09-14"), 14, out / "brooklyn_sep_2026.png")

    split = {name: {"from": str(d["hour"].min()), "to": str(d["hour"].max()), "rows": len(d),
                    "stressed_share": float(d["stressed"].mean())} for name, d in
             [("train", train), ("validation", val), ("test", test)]}
    meta = {"machine": platform.machine(), "python": platform.python_version(),
            "runtime_s": round(time.time() - t0), "split": split, "data": data_summary}
    (out / "metrics.json").write_text(json.dumps({"meta": meta, "results": results.to_dict("records"),
                                                  "importance": importance.to_dict("records")}, indent=2, default=str))

    show = results.copy()
    show["PR-AUC (95% CI)"] = [f"{r.pr_auc:.3f} ({r.pr_auc_lo:.3f}–{r.pr_auc_hi:.3f})" for r in results.itertuples()]
    show = show[["method", "PR-AUC (95% CI)", "alert_precision", "alert_recall", "onset_recall", "false_alerts_per_day"]]
    show.columns = ["Method", "PR-AUC (95% CI)", "Alert precision", "Alert recall", "Onset recall", "False alerts / day"]

    (out / "results.md").write_text(f"""# Results

Generated by `python -m rescuenyc.run` on `{meta['machine']}` in {meta['runtime_s']} s. Real FDNY data.

## Data

{data_summary['rows_raw']:,} raw rows → {data_summary['rows_clean']:,} calls, {data_summary['first_call'][:10]} → {data_summary['last_call'][:10]}.
Held calls: {data_summary['held_share']:.1%}. Median dispatch wait: held {data_summary['median_dispatch_s_held']:.0f} s vs not held {data_summary['median_dispatch_s_not_held']:.0f} s;
high-acuity {data_summary['median_dispatch_s_high']:.0f} s vs low-acuity {data_summary['median_dispatch_s_low']:.0f} s.

| Split | From | To | Borough-hours | Share stressed |
|---|---|---|---|---|
""" + "\n".join(f"| {k} | {v['from'][:10]} | {v['to'][:10]} | {v['rows']:,} | {v['stressed_share']:.1%} |" for k, v in split.items()) + f"""

## Test months: every method, same alert budget (top {config.ALERT_RATE:.0%} of hours)

{md_table(show)}

## Which inputs the full model relies on (test months)

How much PR-AUC drops when one input is shuffled. Bigger = more important.

{md_table(importance.head(10), floats="{:.3f}")}

## How a label is decided (real numbers)

{label_examples(table)}

## Hour by hour: model vs rule vs what happened (test months, real)

{segments}

![Brooklyn, two weeks of September 2026](brooklyn_sep_2026.png)
""")
    print(f"done in {time.time() - t0:.0f}s → {out}")


if __name__ == "__main__":
    main()
