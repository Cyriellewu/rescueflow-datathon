"""Long-run audit, 2005 → latest, one year at a time (memory-safe, resumable).

Reads data/raw_v2/incidents_YYYY-MM.csv per year, cleans with the same rules as the pipeline,
reconstructs the hourly queue with the replay engine, and writes one JSON per year to
artifacts/long_run/YYYY.json. Then docs/long_run_audit.md and submission/long_run_2005_2026.png.

    python scripts/long_run_audit.py            # all years present in data/raw_v2
    python scripts/long_run_audit.py --years 2005 2006
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from rescueflow.data import load_clean  # noqa: E402
from rescueflow.features import hour_grid  # noqa: E402
from rescueflow.stream import backlog_snapshots  # noqa: E402

RAW = ROOT / "data" / "raw_v2"
OUT = ROOT / "artifacts" / "long_run"
MIN = 60.0


def q(s, p):
    s = s.dropna()
    return float(s.quantile(p)) if len(s) else None


def year_stats(y: int) -> dict:
    files = sorted(RAW.glob(f"incidents_{y}-*.csv"))
    if not files:
        return {}
    raw_sev = pd.concat([pd.read_csv(f, usecols=["initial_severity_level_code", "held_indicator"], dtype=str) for f in files])
    df, checks = load_clean(files)
    hi, lo = df[df["high"]], df[~df["high"]]
    hours = hour_grid(df)
    snaps, _ = backlog_snapshots(df, hours)
    hosp = df.dropna(subset=["hosp_arrival", "hosp_end"])
    hosp_min = (hosp["hosp_end"] - hosp["hosp_arrival"]).dt.total_seconds() / MIN
    out = {
        "year": y, "months": len(files), "rows_raw": int(len(raw_sev)), "rows_clean": int(len(df)),
        "calls_per_borough_hour": float(len(df) / max(len(hours), 1) / df["borough"].nunique()),
        "high_share": float(df["high"].mean()),
        "severity_counts": raw_sev["initial_severity_level_code"].value_counts().sort_index().to_dict(),
        "held_share_all": float((raw_sev["held_indicator"] == "Y").mean()),
        "held_share_low": float(lo["held"].mean()) if len(lo) else None,
        "held_share_high": float(hi["held"].mean()) if len(hi) else None,
        "dispatch_high_med_min": q(hi["dispatch_s"] / MIN, 0.5), "dispatch_high_p90_min": q(hi["dispatch_s"] / MIN, 0.9),
        "dispatch_low_med_min": q(lo["dispatch_s"] / MIN, 0.5), "dispatch_low_p90_min": q(lo["dispatch_s"] / MIN, 0.9),
        "travel_high_med_min": q(hi["travel_s"] / MIN, 0.5), "travel_high_p90_min": q(hi["travel_s"] / MIN, 0.9),
        "response_high_med_min": q(hi["response_s"] / MIN, 0.5), "response_high_p90_min": q(hi["response_s"] / MIN, 0.9),
        "hosp_arrival_share": float(df["hosp_arrival"].notna().mean()),
        "hosp_to_close_med_min": q(hosp_min, 0.5), "hosp_to_close_p90_min": q(hosp_min, 0.9),
        "pending_low_mean": float(snaps["pending_low"].mean()), "pending_low_p90": float(snaps["pending_low"].quantile(0.9)),
        "pending_high_mean": float(snaps["pending_high"].mean()),
        "at_hospital_mean": float(snaps["at_hospital"].mean()),
        "pending_low_by_borough": snaps.groupby("borough")["pending_low"].mean().round(2).to_dict(),
        "dispatch_mismatch_rate": checks.get("dispatch_mismatch_rate") if isinstance(checks, dict) else None,
    }
    return out


def table(rows, cols, fmt):
    head = "| year | " + " | ".join(cols) + " |\n|---|" + "---|" * len(cols) + "\n"
    body = "".join(f"| {r['year']} | " + " | ".join(fmt(r.get(c)) for c in cols) + " |\n" for r in rows)
    return head + body


def write_docs(rows):
    f2 = lambda v: "–" if v is None else f"{v:.2f}"  # noqa: E731
    pc = lambda v: "–" if v is None else f"{v:.1%}"  # noqa: E731
    yrs = [r["year"] for r in rows]
    md = [f"# RescueNYC — Long-run audit, {yrs[0]} → {yrs[-1]}\n",
          "Generated by `scripts/long_run_audit.py` from FDNY EMS Incident Dispatch Data (NYC Open Data 76xm-jjuj), one year "
          "at a time with the same cleaning as the pipeline (reopened, transfer and standby rows dropped; durations recomputed "
          "from timestamps). Queue columns come from the replay engine: calls created but not yet assigned at each hour. "
          "2020–2021 are the COVID years and should be read as a regime of their own. High acuity = severity 1–3.\n",
          "## Volume and mix\n",
          table(rows, ["months", "rows_clean", "calls_per_borough_hour", "high_share", "held_share_all", "held_share_low"],
                lambda v: "–" if v is None else (f"{v:,}" if isinstance(v, int) else (f"{v:.1%}" if 0 < abs(v) < 1 else f"{v:.1f}"))),
          "\n## Waiting for a unit (dispatch, minutes)\n",
          table(rows, ["dispatch_high_med_min", "dispatch_high_p90_min", "dispatch_low_med_min", "dispatch_low_p90_min"], f2),
          "\n## On the road and total response, high acuity (minutes)\n",
          table(rows, ["travel_high_med_min", "travel_high_p90_min", "response_high_med_min", "response_high_p90_min"], f2),
          "\n## Hospital handover proxy\n",
          table(rows, ["hosp_arrival_share", "hosp_to_close_med_min", "hosp_to_close_p90_min", "at_hospital_mean"],
                lambda v: "–" if v is None else (f"{v:.1%}" if 0 < v < 1 else f"{v:.1f}")),
          "\n## Reconstructed queue (mean per borough-hour)\n",
          table(rows, ["pending_low_mean", "pending_low_p90", "pending_high_mean"], f2),
          "\n## Severity code set per year (raw counts)\n"]
    codes = sorted({c for r in rows for c in r["severity_counts"]})
    md.append("| year | " + " | ".join(codes) + " |\n|---|" + "---|" * len(codes) + "\n")
    for r in rows:
        md.append(f"| {r['year']} | " + " | ".join(f"{r['severity_counts'].get(c, 0):,}" for c in codes) + " |\n")
    md.append("\n![Long run](../submission/long_run_2005_2026.png)\n")
    (ROOT / "docs" / "long_run_audit.md").write_text("".join(md))


def chart(rows):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    y = [r["year"] for r in rows]
    fig, ax = plt.subplots(2, 2, figsize=(13, 7.5), facecolor="#fcfcfb")
    panels = [("calls_per_borough_hour", "Calls per borough-hour", "#1b4f9c"),
              ("pending_low_mean", "Low-acuity calls waiting for a unit (mean per borough-hour)", "#b03a2e"),
              ("dispatch_low_p90_min", "Low-acuity wait for a unit, p90 (min)", "#b03a2e"),
              ("travel_high_med_min", "High-acuity travel to scene, median (min)", "#1b4f9c")]
    for a, (k, ttl, col) in zip(ax.flat, panels):
        v = [r.get(k) for r in rows]
        a.plot(y, v, color=col, lw=2.2, marker="o", ms=4)
        a.axvspan(2019.5, 2021.5, color="#ebeae6", zorder=0)
        a.set_title(ttl, loc="left", fontsize=11); a.set_facecolor("#fcfcfb")
        a.spines[["top", "right"]].set_visible(False); a.grid(axis="y", color="#ebeae6"); a.set_axisbelow(True)
        a.set_ylim(bottom=0)
    fig.suptitle(f"FDNY EMS, {y[0]}–{y[-1]}: demand, queue, waiting and travel by year (shaded: COVID years)",
                 fontsize=13, weight="bold", x=0.01, ha="left")
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    fig.savefig(ROOT / "submission" / "long_run_2005_2026.png", dpi=170)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--years", type=int, nargs="*")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    years = args.years or sorted({int(p.name[10:14]) for p in RAW.glob("incidents_*.csv")})
    rows = []
    for yr in years:
        path = OUT / f"{yr}.json"
        n_files = len(list(RAW.glob(f"incidents_{yr}-*.csv")))
        if path.exists() and not args.force and json.loads(path.read_text()).get("months") == n_files:
            rows.append(json.loads(path.read_text())); print(f"{yr}: cached"); continue
        r = year_stats(yr)
        if not r:
            continue
        path.write_text(json.dumps(r, indent=1, default=str))
        rows.append(r)
        print(f"{yr}: {r['months']} months, {r['rows_clean']:,} rows, pending_low mean {r['pending_low_mean']:.2f}, "
              f"low p90 wait {r['dispatch_low_p90_min']:.1f} min, held {r['held_share_all']:.1%}")
    write_docs(rows)
    chart(rows)
    print("wrote docs/long_run_audit.md and submission/long_run_2005_2026.png")
